/**
 * Puts the bundled working rules and role agents (extension/kit, copied from claude-mods/kit at build)
 * into ~/.claude and ~/.codex. A file the kit generated is rewritten only by newer rules; a hand-written
 * one gets a managed block; a role file the user edited is never overwritten. No vscode here.
 */
import * as crypto from 'crypto'
import * as fs from 'fs'
import * as path from 'path'
import { ROLE_MODELS, modelOf, withModel } from './roles'

// Same header and version line as claude-mods/kit/kit.mjs, so neither downgrades the other.
export const HEADER = '<!-- generated by claude-mods/kit/setup.mjs from kit/rules.md; edit that file -->\n'
const VERSION = /^<!-- rules-version: (\S+) sha256:([0-9a-f]+) -->$/m
export const BLOCK_START = '<!-- switchboard rules start -->'
export const BLOCK_END = '<!-- switchboard rules end -->'

export const rulesSha = (text: string) => crypto.createHash('sha256').update(text).digest('hex').slice(0, 12)
export const rulesFile = (rules: string, version: string) => `${HEADER}<!-- rules-version: ${version} sha256:${rulesSha(rules)} -->\n\n${rules}`

/** A generated file's rules, without its header, version line and the blank line after them. */
const bodyOf = (text: string) => text.slice(HEADER.length).replace(/^<!-- rules-version: .* -->\n/, '').replace(/^\n/, '')

export function upsertBlock(text: string, rules: string): string {
  const block = `${BLOCK_START}\n${rules.trimEnd()}\n${BLOCK_END}`
  const at = text.indexOf(BLOCK_START), end = text.indexOf(BLOCK_END, at)
  if (at >= 0 && end >= 0) return text.slice(0, at) + block + text.slice(end + BLOCK_END.length)
  return `${text.trimEnd()}${text.trim() ? '\n\n' : ''}${block}\n`
}

export type RulesDecision = { action: 'write' | 'skip'; text?: string; why: string }

export function decideRules(existing: string | undefined, rules: string, version: string): RulesDecision {
  if (existing === undefined) return { action: 'write', text: rulesFile(rules, version), why: 'missing' }
  if (existing.startsWith(HEADER)) {
    if (bodyOf(existing) === rules) return { action: 'skip', why: 'current' }
    const theirs = VERSION.exec(existing)?.[1]
    // ISO times in UTC compare as strings.
    if (theirs && theirs >= version) return { action: 'skip', why: 'kit newer' }
    return { action: 'write', text: rulesFile(rules, version), why: 'older' }
  }
  const text = upsertBlock(existing, rules)
  return text === existing ? { action: 'skip', why: 'block current' } : { action: 'write', text, why: 'block' }
}

/**
 * older: hashes of earlier bundled copies of this role; a file matching one was never edited.
 * A model picked in the gear is not an edit: same as the bundle but for it, skip; an old copy but for it, retune
 * (update, keeping that model).
 */
export function decideAgent(existing: string | undefined, bundled: string, older: string[]): 'install' | 'skip' | 'update' | 'retune' | 'edited' {
  if (existing === undefined) return 'install'
  if (existing === bundled) return 'skip'
  if (older.includes(rulesSha(existing))) return 'update'
  const kitModel = modelOf(bundled)
  if (kitModel && withModel(existing, kitModel) === bundled) return 'skip'
  const asKit = [...ROLE_MODELS, kitModel].flatMap(m => (m ? [withModel(existing, m)] : []))
  return asKit.some(t => t !== undefined && older.includes(rulesSha(t))) ? 'retune' : 'edited'
}

export type SyncResult = { note: string; ready: { claude: boolean; codex: boolean }; changed: string[] }
type Bundle = { rulesVersion: string; history?: Record<string, string[]> }

const read = (p: string) => { try { return fs.readFileSync(p, 'utf8') } catch { return undefined } }

/** write false: decide only, for a dry run. Tools whose folder is missing are left alone. */
export function syncRules(o: { home: string; kit: string; write: boolean }): SyncResult {
  const rules = fs.readFileSync(path.join(o.kit, 'rules.md'), 'utf8')
  const bundle = JSON.parse(fs.readFileSync(path.join(o.kit, 'bundle.json'), 'utf8')) as Bundle
  const changed: string[] = [], edited: string[] = [], failed: string[] = []
  const ready = { claude: false, codex: false }
  const put = (p: string, text: string) => { if (o.write) fs.writeFileSync(p, text) }
  const targets = [['claude', path.join(o.home, '.claude', 'CLAUDE.md')], ['codex', path.join(o.home, '.codex', 'AGENTS.md')]] as const
  for (const [tool, file] of targets) {
    if (!fs.existsSync(path.dirname(file))) continue
    const d = decideRules(read(file), rules, bundle.rulesVersion)
    try {
      if (d.action === 'write') { put(file, d.text!); changed.push(`${path.basename(file)} (${d.why})`) }
      ready[tool] = d.action === 'skip' || o.write
    } catch { failed.push(path.basename(file)) }
  }
  const claude = path.join(o.home, '.claude')
  if (fs.existsSync(claude)) {
    const dir = path.join(claude, 'agents')
    try {
      if (o.write) fs.mkdirSync(dir, { recursive: true })
      for (const name of fs.readdirSync(path.join(o.kit, 'agents')).filter(n => n.endsWith('.md'))) {
        const bundled = fs.readFileSync(path.join(o.kit, 'agents', name), 'utf8')
        const dest = path.join(dir, name)
        const mine = read(dest)
        const act = decideAgent(mine, bundled, bundle.history?.[name] ?? [])
        if (act === 'install' || act === 'update') { put(dest, bundled); changed.push(`${name} (${act === 'install' ? 'added' : 'updated'})`) }
        else if (act === 'retune') { put(dest, withModel(bundled, modelOf(mine!)!) ?? bundled); changed.push(`${name} (updated, your model kept)`) }
        else if (act === 'edited') {
          edited.push(name)
          // Claude Code reads only *.md, so the new copy sits beside the edited one unused.
          if (read(`${dest}.switchboard-new`) !== bundled) { put(`${dest}.switchboard-new`, bundled); changed.push(`${name}.switchboard-new`) }
        }
      }
    } catch { failed.push('agents') }
  }
  const parts = [
    changed.length ? `updated ${changed.join(', ')}` : '',
    edited.length ? `${edited.join(', ')} edited by you, new copy kept as .switchboard-new` : '',
    failed.length ? `could not write ${failed.join(', ')}` : '',
  ].filter(Boolean)
  return { note: `Rules and roles: ${parts.length ? parts.join('; ') : 'up to date'}`, ready, changed }
}

/** The kit's whole content, so activation syncs once per change of it. */
export function kitHash(kit: string): string {
  const h = crypto.createHash('sha256')
  for (const f of ['rules.md', 'bundle.json', ...fs.readdirSync(path.join(kit, 'agents')).sort().map(n => `agents/${n}`)]) h.update(f).update(fs.readFileSync(path.join(kit, f)))
  return h.digest('hex')
}

/** After the last sync: whether each tool's rules file holds the rules. Until then, assume so. */
export const rulesState = { ready: { claude: true, codex: true }, kit: '' }

/** A chat whose rules file could not be written is pointed at the bundled copy; an empty message stays empty. */
export const withPointer = (text: string, ready: boolean, kit: string) =>
  ready || !text ? text : `${text}\n\nFollow the working style in ${kit}/rules.md; role briefs are in ${kit}/agents.`
